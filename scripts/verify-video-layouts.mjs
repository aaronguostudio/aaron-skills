// Installed-only synthetic media acceptance. No private capture or paid provider.
import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import {readFileSync,writeFileSync,mkdirSync,mkdtempSync,existsSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {dirname,join,resolve} from 'node:path';
import {pathToFileURL} from 'node:url';

const release=resolve(process.argv[2]??'');
const config=JSON.parse(readFileSync(join(release,'installed.json'),'utf8'));
process.env.PATH=[...Object.values(config.tools).map(p=>dirname(p)),process.env.PATH].join(process.platform==='win32'?';':':');
const root=process.argv[3]?resolve(process.argv[3]):mkdtempSync(join(tmpdir(),'aaron-layout-acceptance-'));
mkdirSync(root,{recursive:true});
const {makeFixture}=await import(pathToFileURL(join(release,'packages/demo/walkthrough/make-fixture.ts')).href);
const {main}=await import(pathToFileURL(join(release,'packages/demo/walkthrough/render-walkthrough.ts')).href);
const {prepare}=await import(pathToFileURL(join(release,'packages/demo/walkthrough/render-walkthrough.ts')).href);
const {stepMinMs,cardMinMs}=await import(pathToFileURL(join(release,'packages/demo/walkthrough/narration.ts')).href);
const {mapBox}=await import(pathToFileURL(join(release,'packages/demo/remotion/src/projects/walkthrough-video/presentation/layout.ts')).href);
const run=join(root,'capture');makeFixture(run);
// Add several checked focus regions without changing the recorded pixels.
const steps=JSON.parse(readFileSync(join(run,'steps.json'),'utf8'));
steps[3].endMs+=400;
steps[3].focus=[{x:600,y:420,w:400,h:40},{x:560,y:260,w:480,h:360}].map(box=>({fromMs:steps[3].startMs,toMs:steps[3].endMs,box}));
writeFileSync(join(run,'steps.json'),JSON.stringify(steps));
const hash=path=>createHash('sha256').update(readFileSync(path)).digest('hex');
const originals=Object.fromEntries(['video.webm','capture.json','steps.json'].map(f=>[f,hash(join(run,f))]));
const python=join(release,'.venv',process.platform==='win32'?'Scripts':'bin',process.platform==='win32'?'python.exe':'python3');
execFileSync(python,['-c',`from PIL import Image, ImageDraw
import sys, wave, math, struct
from pathlib import Path
p=Path(sys.argv[1])
for name,ink in [('light','white'),('dark','#173CA8')]:
 im=Image.new('RGBA',(400,100),(0,0,0,0));d=ImageDraw.Draw(im)
 d.polygon([(50,4),(94,50),(50,96),(6,50)],fill='#FFD229',outline=ink,width=8)
 d.text((112,34),'NORTHSTAR',fill=ink,font_size=34)
 im.save(p/(name+'.png'))
w=wave.open(str(p/'tone.wav'),'wb');w.setparams((1,2,44100,0,'NONE','not compressed'))
w.writeframes(b''.join(struct.pack('<h',int(2200*math.sin(i*2*math.pi*440/44100))) for i in range(44100*8)));w.close()
`,root]);
const text='Review the synthetic form before confirming. The complete transcript is separate from the short step caption. The application screen, pointer and checked outlines share one uniform placement transform. This local tone tests imported timing without generating a voice. The original evidence and audio remain unchanged when the layout moves. Every page keeps the remaining words available rather than hiding them behind an ellipsis.';
const audio=join(root,'audio.json');
writeFileSync(audio,JSON.stringify({version:1,aiGenerated:false,clips:[{at:steps[0].id,file:'tone.wav',text}]}));
const toneHash=hash(join(root,'tone.wav'));
const evidence=[];
const cases=[
  {screenPlacement:'top',annotationMode:'caption',annotationRatio:.22},
  {screenPlacement:'bottom',annotationMode:'transcript',annotationRatio:.3,padding:20,gap:16,canvas:{width:1280,height:960}},
  {screenPlacement:'left',annotationMode:'transcript',annotationRatio:.32,padding:24,gap:20,canvas:{width:1600,height:1000}},
  {screenPlacement:'right',annotationMode:'caption',annotationRatio:.28,padding:24,gap:16},
];
for(const layout of cases){
  const name=layout.screenPlacement,file=join(root,`${name}.json`),dir=join(root,name),preview=join(dir,'preview');
  writeFileSync(file,JSON.stringify({version:2,template:'professional',title:'Review the synthetic form',subtitle:'A layout and brand acceptance example',theme:{preset:'blue-lavender'},cover:{preset:'cobalt-signal'},brand:{name:'Northstar',logo:'light.png',logoVariants:{light:'light.png',dark:'dark.png'},logoContainsName:true,logoProvenance:{source:'Synthetic Northstar fixture generated by this verifier',role:'corporate',verified:true}},intro:{durationMs:1500,soundPreset:'none'},outro:{durationMs:1200,title:'Ready to review',subtitle:'No business transaction was performed'},layout}));
  assert.equal(await main([run,'--presentation',file,'--audio',audio,'--preview','--cover','--out',join(preview,'walkthrough.mp4')]),0);
  assert.ok(existsSync(join(preview,'body-preview.png')));assert.ok(!existsSync(join(preview,'walkthrough.mp4')));
  const out=join(dir,'walkthrough.mp4');
  assert.equal(await main([run,'--presentation',file,'--audio',audio,'--cover','--stills','--out',out]),0);
  const m=JSON.parse(readFileSync(join(dir,'render-manifest.json'),'utf8'));
  const probe=JSON.parse(execFileSync(config.tools.ffprobe,['-v','error','-show_streams','-show_format','-of','json',out],{encoding:'utf8'}));
  const video=probe.streams.find(s=>s.codec_type==='video');
  assert.equal(video.codec_name,'h264');assert.equal(video.width,m.geometry.width);assert.equal(video.height,m.geometry.height);
  assert.equal(m.resolvedPalette.body.background,'#173CA8');assert.equal(m.resolvedPalette.outro.background,'#173CA8');
  assert.ok(m.logoChecks.every(s=>s.width===400&&s.height===100&&s.hasTransparency));
  assert.deepEqual(m.logoChecks.flatMap(s=>s.surfaces.map(s=>s.surface)).sort(),['body','cover','intro','outro']);
  execFileSync(config.tools.ffmpeg,['-v','error','-i',out,'-f','null','-']);
  const plan=prepare(run,out,[],undefined,{titleBaseMs:1500,endBaseMs:1200,stepMinMs:stepMinMs(steps,m.narration),...cardMinMs(m.narration)});
  const frames=[['intro',.8],['body',plan.stills[0].frame/30],['wait-end',plan.stills[2].frame/30],['focus',plan.stills[3].frame/30],['transcript-late',Number(probe.format.duration)-2],['outro',Number(probe.format.duration)-.4]];
  for(const [label,at] of frames)execFileSync(config.tools.ffmpeg,['-v','error','-ss',String(at),'-i',out,'-frames:v','1','-update','1',join(dir,`qa-${label}.png`)]);
  // Distinct gold pixels must survive on the real rendered cover, annotation and outro.
  execFileSync(python,['-c',`from PIL import Image
import sys,json
from pathlib import Path
p=Path(sys.argv[1]);m=json.loads((p/'render-manifest.json').read_text());b=m['geometry']['annotation']
for name in ['cover.png','qa-body.png','qa-outro.png']:
 im=Image.open(p/name).convert('RGB')
 if name=='qa-body.png':im=im.crop((int(b['x']),int(b['y']),int(b['x']+b['w']),int(b['y']+b['h'])))
 count=sum(1 for r,g,b in im.getdata() if r>210 and 150<g<235 and b<80)
 assert count>8,(name,count)
`,dir]);
  for(const [file,before] of Object.entries(originals))assert.equal(hash(join(run,file)),before);
  assert.equal(hash(join(root,'tone.wav')),toneHash);
  // Existing outlines add six horizontal and five vertical capture pixels.
  const box=mapBox({x:594,y:415,w:412,h:50},m.geometry.screen);
  assert.ok(box.x>=m.geometry.screen.x&&box.y>=m.geometry.screen.y);
  execFileSync(python,['-c',`from PIL import Image
import sys,json
im=Image.open(sys.argv[1]).convert('RGB');b=json.loads(sys.argv[2]);y=round(b['y'])
n=sum(1 for x in range(round(b['x'])+12,round(b['x']+b['w'])-12) for dy in range(-4,5) if 35<im.getpixel((x,y+dy))[0]<110 and 60<im.getpixel((x,y+dy))[1]<150 and im.getpixel((x,y+dy))[2]>190)
assert n>b['w']*.3,('transformed focus outline is misaligned',n,b)
`,join(dir,'qa-focus.png'),JSON.stringify(box)]);
  evidence.push({layout:name,dimensions:[video.width,video.height],seconds:Number(probe.format.duration),preview:true,fullDecode:true,logoPixels:true,geometry:m.geometry});
}
const report={passed:true,platform:process.platform,scope:'Installed synthetic fixture; four layouts, transparent wide wordmark variants, uniform geometry, multiple focus boxes, waits, imported tone and transcript; no live voice/provider or platform certification',root,release,originals,evidence};
writeFileSync(join(root,'acceptance.json'),JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify(report,null,2));
